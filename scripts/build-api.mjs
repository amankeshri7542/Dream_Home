// Bundles the AI server (server/*.ts plus the pure src/ai and src/domain code it
// uses) into one self-contained Vercel function: api/index.js. vercel.json
// rewrites every /api/* request to it. The output is committed: run this after
// changing anything under server/ or src/ai/ (the gate checks it's current).
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
await build({
  absWorkingDir: root,
  entryPoints: ["server/api.ts"],
  outfile: "api/index.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  // Installed by Vercel from package.json dependencies.
  external: ["@anthropic-ai/sdk", "@vercel/blob"],
  legalComments: "none",
  banner: { js: "// Generated by scripts/build-api.mjs from server/*.ts — do not edit by hand." },
  logLevel: "warning",
});
console.log("Built api/index.js");
