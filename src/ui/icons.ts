export type IconName = keyof typeof Icon;

/** A recognisable glyph per room kind (study/prayer use their own). */
export function roomIcon(kind: RoomKind, name = ""): LucideIcon {
  if (/study|office/i.test(name)) return BookOpen;
  if (/prayer|pooja|puja/i.test(name)) return Flame;
  return {
    living: Sofa,
    kitchen: CookingPot,
    bedroom: BedDouble,
    bathroom: Bath,
    dining: UtensilsCrossed,
    utility: WashingMachine,
    shop: Store,
  }[kind];
}
